export function registerHelperTools(server: McpServer) {
  server.tool(
    "sdk_lookup",
    "Query GTA SA enum constants, model IDs, weapon IDs, stat IDs, radio stations, tuning mods, cheat names, or SCM opcodes.",
    {
      category: z.enum([
        "all",
        "weapons",
        "vehicles",
        "weather",
        "stats",
        "radio",
        "pedTypes",
        "tasks",
        "tuning",
        "cheats",
        "commonOpcodes",
      ]).describe("Category to inspect"),
      query: z.string().optional().describe("Search term (filter by key name or value)"),
    },
    async ({ category, query }) => {
      if (category !== "all" && SDK_REGISTRY[category]) {
        let entries = SDK_REGISTRY[category];
        if (query) {
          const q = query.toLowerCase();
          entries = Object.fromEntries(
            Object.entries(entries).filter(([k, v]) =>
              k.toLowerCase().includes(q) || String(v).toLowerCase().includes(q)
            )
          );
        }
        return { content: [{ type: "text", text: JSON.stringify(entries, null, 2) }] };
      }

      if (category === "all") {
        if (!query) {
          return { content: [{ type: "text", text: JSON.stringify(Object.keys(SDK_REGISTRY), null, 2) }] };
        }
        const q = query.toLowerCase();
        const results: Record<string, Record<string, string | number>> = {};
        for (const [catName, catData] of Object.entries(SDK_REGISTRY)) {
          const filtered = Object.fromEntries(
            Object.entries(catData).filter(([k, v]) =>
              k.toLowerCase().includes(q) || String(v).toLowerCase().includes(q)
            )
          );
          if (Object.keys(filtered).length > 0) {
            results[catName] = filtered;
          }
        }
        return { content: [{ type: "text", text: JSON.stringify(results, null, 2) }] };
      }

      return { content: [{ type: "text", text: "Category not found." }] };
    }
  );
}
